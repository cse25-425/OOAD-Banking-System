package bac.com.mosweu.ooad_project.database;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/** Selects the persistent H2 file and creates any missing application tables. */
public class DatabaseInitializer {
    /** Database file base path; it can be overridden with the {@code bank.db.path} system property. */
    private static final Path DB_FILE = Path.of(System.getProperty(
                    "bank.db.path",
                    Path.of(System.getProperty("user.home"), ".ooad-banking", "bankdb")
                            .toString()))
            .toAbsolutePath()
            .normalize();

    /** JDBC URL for the file-backed database, allowing H2 automatic server mode. */
    public static final String URL = "jdbc:h2:file:" + DB_FILE.toString().replace('\\', '/') + ";AUTO_SERVER=TRUE";

    public static final String USER = "sa";
    public static final String PASSWORD = "";

    /** Creates the database directory and idempotently creates the schema without seeding customer data. */
    public static void initialize() throws IOException, SQLException {
        Files.createDirectories(DB_FILE.getParent());

        try (Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
                Statement stmt = conn.createStatement()) {

            stmt.execute("""
                CREATE TABLE IF NOT EXISTS Customer (
                    customerId VARCHAR(50) PRIMARY KEY,
                    firstName VARCHAR(50) NOT NULL,
                    surname VARCHAR(50) NOT NULL,
                    address VARCHAR(255),
                    username VARCHAR(50) NOT NULL UNIQUE,
                    password VARCHAR(255) NOT NULL,
                    failedLoginAttempts INT NOT NULL DEFAULT 0,
                    lockedUntil TIMESTAMP
                )
                """);
            stmt.execute("ALTER TABLE Customer ADD COLUMN IF NOT EXISTS address VARCHAR(255)");
            stmt.execute("ALTER TABLE Customer ADD COLUMN IF NOT EXISTS failedLoginAttempts INT NOT NULL DEFAULT 0");
            stmt.execute("ALTER TABLE Customer ADD COLUMN IF NOT EXISTS lockedUntil TIMESTAMP");
            stmt.execute("ALTER TABLE Customer ALTER COLUMN password VARCHAR(255)");

            stmt.execute("""
                CREATE TABLE IF NOT EXISTS Account (
                    accountNumber VARCHAR(50) PRIMARY KEY,
                    customerId VARCHAR(50) NOT NULL,
                    accountType VARCHAR(50) NOT NULL,
                    branch VARCHAR(50),
                    employerName VARCHAR(100),
                    employerAddress VARCHAR(255),
                    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                    balance DECIMAL(19, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
                    FOREIGN KEY (customerId) REFERENCES Customer(customerId)
                )
                """);
            stmt.execute("ALTER TABLE Account ADD COLUMN IF NOT EXISTS branch VARCHAR(50)");
            stmt.execute("ALTER TABLE Account ADD COLUMN IF NOT EXISTS employerName VARCHAR(100)");
            stmt.execute("ALTER TABLE Account ADD COLUMN IF NOT EXISTS employerAddress VARCHAR(255)");
            stmt.execute("ALTER TABLE Account ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'");
            stmt.execute("ALTER TABLE Account ALTER COLUMN balance DECIMAL(19, 2)");
            ensureAccountBalanceConstraint(conn);

            stmt.execute("""
                CREATE TABLE IF NOT EXISTS BankTransaction (
                    transactionId BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    accountNumber VARCHAR(50) NOT NULL,
                    transactionType VARCHAR(20) NOT NULL
                        CHECK (transactionType IN ('DEPOSIT', 'WITHDRAWAL', 'INTEREST')),
                    amount DECIMAL(19, 2) NOT NULL CHECK (amount > 0),
                    interestMonth DATE,
                    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (accountNumber) REFERENCES Account(accountNumber)
                )
                """);
            stmt.execute("ALTER TABLE BankTransaction ADD COLUMN IF NOT EXISTS interestMonth DATE");
            ensureTransactionTypeConstraint(conn);
            stmt.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS UX_BANK_TRANSACTION_MONTH
                ON BankTransaction(accountNumber, transactionType, interestMonth)
                """);
        }
    }

    private static void ensureAccountBalanceConstraint(Connection conn) throws SQLException {
        boolean hasBalanceCheck = false;
        try (Statement query = conn.createStatement();
                ResultSet rs = query.executeQuery("""
                    SELECT cc.CHECK_CLAUSE
                    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
                    JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
                      ON tc.CONSTRAINT_CATALOG = cc.CONSTRAINT_CATALOG
                     AND tc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA
                     AND tc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
                    WHERE tc.TABLE_SCHEMA = 'PUBLIC'
                      AND tc.TABLE_NAME = 'ACCOUNT'
                      AND tc.CONSTRAINT_TYPE = 'CHECK'
                    """)) {
            while (rs.next()) {
                String clause = rs.getString("CHECK_CLAUSE").toUpperCase(Locale.ROOT);
                if (clause.contains("BALANCE") && clause.contains(">=")) {
                    hasBalanceCheck = true;
                    break;
                }
            }
        }

        if (!hasBalanceCheck) {
            try (Statement add = conn.createStatement()) {
                add.execute("""
                    ALTER TABLE Account
                    ADD CONSTRAINT CK_ACCOUNT_NON_NEGATIVE_BALANCE CHECK (balance >= 0)
                    """);
            }
        }
    }

    private static void ensureTransactionTypeConstraint(Connection conn) throws SQLException {
        List<String> constraintsToReplace = new ArrayList<>();
        boolean supportsInterest = false;
        try (Statement query = conn.createStatement();
                ResultSet rs = query.executeQuery("""
                    SELECT tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE
                    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
                    JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
                      ON tc.CONSTRAINT_CATALOG = cc.CONSTRAINT_CATALOG
                     AND tc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA
                     AND tc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
                    WHERE tc.TABLE_SCHEMA = 'PUBLIC'
                      AND tc.TABLE_NAME = 'BANKTRANSACTION'
                      AND tc.CONSTRAINT_TYPE = 'CHECK'
                    """)) {
            while (rs.next()) {
                String clause = rs.getString("CHECK_CLAUSE").toUpperCase(Locale.ROOT);
                if (clause.contains("TRANSACTIONTYPE")) {
                    if (clause.contains("'INTEREST'")) {
                        supportsInterest = true;
                    } else {
                        constraintsToReplace.add(rs.getString("CONSTRAINT_NAME"));
                    }
                }
            }
        }

        for (String constraint : constraintsToReplace) {
            String name = constraint.replace("\"", "\"\"");
            try (Statement drop = conn.createStatement()) {
                drop.execute("ALTER TABLE BankTransaction DROP CONSTRAINT \"" + name + "\"");
            }
        }

        if (!supportsInterest) {
            try (Statement add = conn.createStatement()) {
                add.execute("""
                    ALTER TABLE BankTransaction
                    ADD CONSTRAINT CK_BANK_TRANSACTION_TYPE
                    CHECK (transactionType IN ('DEPOSIT', 'WITHDRAWAL', 'INTEREST'))
                    """);
            }
        }
    }
}
